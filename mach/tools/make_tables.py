#!/usr/bin/env python3
"""Writes tables.h, Mach's constant tables: run it after changing a shape here,
and commit both.

  - Three band-limited single-cycle waves (organ, pad, siren), each at
    nine levels: level L keeps the harmonics up to 256 >> L (255 at level 0),
    so the engine can pick the level the listener's Doppler-shifted pitch
    allows, and crossfade to the next.
  - A sine for the bell's partials and the voice's formants.
  - The bell's two decay envelopes over one strike period.
  - The voice's pulse window (one fundamental period).
  - 2^x over one octave, for the siren's sweep.
All Q15, 16-bit."""
import math
import pathlib

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
WAVE = 512      # samples a cycle (a guard sample follows)
LEVELS = 9


def band_limited(spectrum, top):
    """One cycle from complex harmonic amplitudes (index k = harmonic k), cut at `top`."""
    bins = np.zeros(WAVE // 2 + 1, complex)
    for k in range(1, min(top, WAVE // 2 - 1) + 1):
        bins[k] = spectrum[k]
    return np.fft.irfft(bins, WAVE) * WAVE / 2


def spectrum(amplitude, seed=0):
    """Harmonic amplitudes (k = 1 .. 255) with phases from a fixed hand, so
    rich tables keep a low crest factor."""
    rng = np.random.default_rng(seed)
    bins = np.zeros(WAVE // 2 + 1, complex)
    for k in range(1, WAVE // 2):
        a = amplitude(k)
        if a:
            phase = rng.uniform(0, 2 * np.pi) if seed else -np.pi / 2
            bins[k] = a * np.exp(1j * phase)
    return bins


def organ(k):
    # Drawbars 8', 4', 2 2/3', 2', 1 3/5', 1 1/3', 1' (harmonics 1, 2, 3, 4, 5, 6, 8)
    return {1: 1.0, 2: 0.62, 3: 0.46, 4: 0.36, 5: 0.10, 6: 0.20, 8: 0.17}.get(k, 0.0)


def pad(k):
    # A bowed, string-like spectrum: 1 / k^1.15, a soft body formant near the
    # 3rd-5th harmonics, rolling away above the 20th.
    body = 1 + 0.5 * np.exp(-((k - 4) / 2.0) ** 2)
    return body / k ** 1.15 * np.exp(-k / 28)


def siren(k):
    # A siren's chopped air, softened for a lead: odd harmonics at 1 / k^1.6,
    # a little of the even.
    return (1.0 if k % 2 else 0.18) / k ** 1.6


def wave_levels(amplitude, seed):
    full = spectrum(amplitude, seed)
    levels = [band_limited(full, max(1, (256 >> lv) - (1 if lv == 0 else 0))) for lv in range(LEVELS)]
    peak = max(np.abs(lv).max() for lv in levels)
    return [lv / peak * 0.95 for lv in levels]


def q15(values):
    return [int(round(max(-1, min(1, v)) * 32767)) for v in values]


def array(name, kind, values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return f"const {kind} {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};"


out = ["#pragma once",
       "// Generated by tools/make_tables.py: do not edit by hand.",
       '#include <opxy/types.hpp>',
       "",
       "namespace mach {",
       "namespace tables {",
       f"const opxy::u32 wave_size = {WAVE}, wave_levels = {LEVELS};"]

for name, amplitude, seed in (("organ", organ, 0), ("pad", pad, 7), ("siren", siren, 0)):
    rows = []
    for level in wave_levels(amplitude, seed):
        rows.extend(q15(list(level) + [level[0]]))
    out.append(f"// {name}: {LEVELS} levels of {WAVE} + 1 samples")
    out.append(array(name, "opxy::i16", rows))

SINE = 4096
out.append(f"const opxy::u32 sine_bits = 12;   // {SINE} samples a cycle")
out.append(array("sine", "opxy::i16", q15([math.sin(2 * math.pi * i / SINE) for i in range(SINE)])))

# The bell: one strike period, 1024 steps. The hum and prime ring long, the
# tierce and nominal half as long; both close to exactly zero at the period's
# end, so the next strike (or, played backwards, the previous one) meets silence.
ENV = 1024
def taper(u):
    return 1 - u ** 10
bell_low = [math.exp(-u / 0.55) * taper(u) for u in (i / ENV for i in range(ENV))]
bell_high = [math.exp(-u / 0.22) * taper(u) for u in (i / ENV for i in range(ENV))]
out.append(f"const opxy::u32 envelope_bits = 10;   // {ENV} steps a period")
out.append(array("bell_low", "opxy::i16", q15(bell_low)))
out.append(array("bell_high", "opxy::i16", q15(bell_high)))
# The high ring over the low: the tierce's and nominal's share, riding on the
# low ring's envelope.
out.append(array("bell_tone", "opxy::i16", q15([h / l if l > 0 else 0 for h, l in zip(bell_high, bell_low)])))

# The voice: a glottal pulse's window over one period, opening and closing
# smoothly (a leaning Hann window), so the formant bursts sing rather than buzz.
out.append(array("pulse", "opxy::i16", q15([(0.5 - 0.5 * math.cos(2 * math.pi * u)) * (1 - 0.45 * u)
                                            for u in (i / ENV for i in range(ENV))])))

# log2(1 + j / 32), j = 0 .. 32, Q16: tuning's logarithm.
out.append(array("log2", "opxy::u32", [int(round(65536 * math.log2(1 + j / 32))) for j in range(33)], 11))

# 2^x for x in [0, 1], 65 points, Q14 (1.0 = 16384).
out.append(array("exp2", "opxy::u16", [int(round(16384 * 2 ** (i / 64))) for i in range(65)]))

# The compression gain 1.25 rho / (0.25 + rho) for rho = j / 16, j = 0 .. 128,
# Q30: a root heard faster than its source runs is louder (1 at rho = 1), up
# to a quarter as loud again, so the caustic at the cone stays in bounds and a
# chord's notes, all at their caustic at once, don't pile up.
out.append(array("doppler", "opxy::i32", [int(round(1.25 * r / (0.25 + r) * (1 << 30))) for r in (j / 16 for j in range(129))], 8))

# The air's low-pass: what it lets through, 1 / (1 + w), for w = j / 8,
# j = 0 .. 256, Q15 (the coefficient is 1 minus it).
out.append(array("open", "opxy::u16", [int(round(32767 / (1 + j / 8))) for j in range(257)]))

# sqrt(x) for x = j / 64, j = 16 .. 64, Q15: the distance law's root.
out.append(array("root", "opxy::u16", [int(round(32768 * math.sqrt((16 + j) / 64))) for j in range(49)]))

# 1 / x at the middle of each sixteenth of [0.5, 1), then of each 64th, Q30:
# the reciprocal's first guesses (precise, then quick).
out.append(array("inverse", "opxy::u32", [int(round((1 << 30) / (0.5 + (j + 0.5) / 32))) for j in range(16)] +
                 [int(round((1 << 30) / (0.5 + (j + 0.5) / 128))) for j in range(64)], 8))

out += ["}", "}", ""]
(ROOT / "tables.h").write_text("\n".join(out))
print("wrote", ROOT / "tables.h")
