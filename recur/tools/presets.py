#!/usr/bin/env python3
"""Recur's presets: writes them into definition.json, and presets.h for
tools/render.cpp and the tests. Run it after changing one, and commit all
three; then tools/make_regions.py, which trims each preset's region by TRIMS."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
MAPS = ["cat", "baker", "gold", "pell", "shear", "hex"]
GRIDS = [2, 4, 8]
SLICES = ["hiss", "1/64", "1/32", "1/16", "1/8", "1/4"]
RATES = ["off", "4 bars", "2 bars", "1 bar", "1/2", "1/4", "1/8", "1/16"]
CHORDS = ["off", "dtun", "oct", "5th", "maj", "min", "harm"]

# name: fit, grid, slice, map, step, rate, depth, chrd, and the source it's heard on.
PRESETS = {
    "Recur": (0, 4, "1/16", "cat", 0, "1 bar", 0.7, "off", "drums"),
    "Stutter": (0, 8, "1/32", "shear", 0, "1/4", 0.5, "off", "drums"),
    "Phrase": (0, 4, "1/8", "gold", 0, "1 bar", 1, "off", "phrase"),
    "Riffle": (0, 4, "1/16", "baker", 0, "1 bar", 1, "off", "drums"),
    "Glitch": (0, 8, "1/64", "pell", 0, "1/8", 1, "off", "drums"),
    "Chorale": (0, 2, "1/4", "hex", 0, "1 bar", 1, "min", "phrase"),
    "Frozen": (0, 8, "1/32", "cat", 0.601, "off", 1, "off", "drums"),   # step 3 of 6
    "Shred": (0, 4, "hiss", "cat", 0, "1/16", 1, "off", "phrase"),
}


# A bar at 120 BPM, frames.
BAR = 88200
# Each preset's trim of the break, (start, end) in frames: bar 1, unless its
# grid and slice fill two bars at 120 BPM (8 x 8 of 1/32, 4 x 4 of 1/8), or,
# for Shred, its hiss square where the old pos 0.1 put it, on the snare.
TRIMS = {name: (0, BAR) for name in PRESETS}
TRIMS.update({"Stutter": (0, 2 * BAR), "Phrase": (0, 2 * BAR), "Frozen": (0, 2 * BAR), "Shred": (34870, 34870 + BAR)})


def middle(i, n):
    return round((i + 0.5) / n, 6)


def values(p):
    fit, grid, slc, mp, step, rate, depth, chord, _ = p
    return {"fit": fit, "grid": middle(GRIDS.index(grid), 3), "slice": middle(SLICES.index(slc), 6),
            "map": middle(MAPS.index(mp), 6), "step": step, "rate": middle(RATES.index(rate), 8),
            "depth": depth, "chrd": middle(CHORDS.index(chord), 7)}


def main():
    definition = json.loads(ROOT.joinpath("definition.json").read_text())
    definition["presets"] = {name: values(p) for name, p in PRESETS.items()}
    ROOT.joinpath("definition.json").write_text(json.dumps(definition, indent=2) + "\n")
    rows = []
    for name, p in PRESETS.items():
        v = values(p)
        controls = ", ".join(str(v[k]) for k in ("fit", "grid", "slice", "map", "step", "rate", "depth", "chrd"))
        rows.append(f'    {{"{name}", "{p[8]}", {{{controls}}}, {TRIMS[name][0]}, {TRIMS[name][1]}}},')
    ROOT.joinpath("tools/presets.h").write_text(
        "#pragma once\n// Generated by tools/presets.py; edit the generator, not this file.\n"
        "// Each preset's controls, and its trim of the break (begin, end) in frames.\n"
        "struct Preset { const char* name; const char* source; double values[8]; unsigned begin, end; };\n"
        "const Preset presets[] = {\n" + "\n".join(rows) + "\n};\n")
    print("wrote", len(PRESETS), "presets")


if __name__ == "__main__":
    main()
