#!/usr/bin/env python3
"""Writes tables.h, Recur's constant tables. Run it after changing one, and commit both."""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def rows(values, per=8):
    return "\n".join("    " + ", ".join(str(v) for v in values[i:i + per]) + "," for i in range(0, len(values), per))


quarter = [round(32767 * math.sin(math.pi / 2 * i / 64)) for i in range(65)]
semitones = [round(65536 * 2 ** (i / 12)) for i in range(12)]
rev8 = [int(f"{i:08b}"[::-1], 2) for i in range(256)]

ROOT.joinpath("tables.h").write_text(f"""#pragma once
// Generated by tools/make_tables.py; edit the generator, not this file.
#include <opxy/types.hpp>

namespace recur {{

// A quarter sine, Q15, 64 steps and an end: the equal-power crossfade.
const opxy::i16 quarter_sine[65] = {{
{rows(quarter)}
}};

// 2^(n/12), Q16, for the semitones of an octave.
const opxy::u32 semitone_table[12] = {{
{rows(semitones, 6)}
}};

// Each byte with its bits reversed: the baker's map reads y backwards.
const opxy::u8 reversed8[256] = {{
{rows(rev8, 16)}
}};
}}
""")
