#!/usr/bin/env python3
"""Writes tests/presets.h, the presets as definition.json has them, for the
sound, screen and scenes tests. Run it after changing a preset."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
d = json.loads((ROOT / "definition.json").read_text())
ids = [p["id"] for p in d["parameters"]]
lines = ["// Generated by tools/make_presets.py from definition.json. Edit that, not this file.",
         "#pragma once",
         "",
         "// The presets, in definition.json's order of controls: " + ", ".join(ids) + ".",
         "struct Preset { const char* name; double c[8]; };",
         "const Preset presets[] = {"]
for name, values in d["presets"].items():
    lines.append(f'    {{"{name}", {{{", ".join(repr(float(values[i])) for i in ids)}}}}},')
lines += ["};", f"const unsigned preset_count = {len(d['presets'])};", ""]
(ROOT / "tests" / "presets.h").write_text("\n".join(lines))
print("tests/presets.h:", len(d["presets"]), "presets")
