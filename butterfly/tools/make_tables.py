#!/usr/bin/env python3
"""Writes tables.h: Butterfly's constant tables. Run it after changing a
table, and commit both.

The spectrum: Harper's equation on a chain of 17 sites, m = -8..8,

    H psi_m = psi_(m+1) + psi_(m-1) + 2 lambda cos(2 pi alpha m) psi_m,

solved in double precision (numpy's eigh) on a grid of flux (0 to 1/2 in
128ths and at every fraction p/q with q <= 8, so that snap lands on exact
spectra: the spectrum repeats with period 1 and mirrors about 1/2, since m
is whole) and coupling (seven values, closest round the self-dual point). The
chain is mirror-symmetric (the potential's phase is 0 at the middle site),
so each state's amplitude is stored for the half-chain, distance 0..8 from
the middle, and the two members of a mirror pair whose energies agree to
2^-10 are merged into one state carrying both (the other kept silent at the
same energy): they ring at one pitch.

Also sine, exp2, log2 and reciprocal seeds, and the snap fractions, as
Talbot's: the Farey sequence of order 8, each basin reaching to the mediants."""
import math
import pathlib
from fractions import Fraction

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]


def rows(values, per=16):
    values = [str(v) for v in values]
    return ",\n    ".join(", ".join(values[i:i + per]) for i in range(0, len(values), per))


DECLARATIONS, DEFINITIONS = [], []


def table(kind, name, values, comment, per=16):
    """A table: declared in tables.h, defined once in tables_data.h (a const
    array at namespace scope would otherwise be copied into every object that
    includes it: the engine's and the display's)."""
    DECLARATIONS.append(f"// {comment}\nextern const {kind} {name}[{len(values)}];")
    DEFINITIONS.append(f"extern const {kind} {name}[{len(values)}] = {{\n    {rows(values, per)}}};\n")
    return ""


SINE_BITS = 12
sine = [round(32767 * math.sin(2 * math.pi * k / 2 ** SINE_BITS)) for k in range(2 ** SINE_BITS + 1)]
exp2 = [round(32768 * 2 ** (k / 256)) for k in range(257)]                    # Q15, 1 to 2
log2m = [round(65536 * math.log2(1 + k / 256)) for k in range(257)]             # Q16, 0 to 1
recip = [round(2 ** 30 / (2 ** 15 + (k + 0.5) * 128)) for k in range(256)]      # 2^30 / m, m in [2^15, 2^16)

# The snap fractions: the Farey sequence of order 8, 0 to 1.
farey = sorted({Fraction(p, q) for q in range(1, 9) for p in range(0, q + 1)})


def q32(f):
    return round(f * 2 ** 32) & 0xFFFFFFFF


f_u32 = [q32(f) for f in farey]
med = [Fraction(a.numerator + b.numerator, a.denominator + b.denominator) for a, b in zip(farey, farey[1:])]
m_u32 = [q32(m) for m in med]
lo = [(m - a) for a, m in zip(farey, med)]          # an interval's lower half: its left fraction's basin
hi = [(b - m) for b, m in zip(farey[1:], med)]      # its upper half: the right fraction's basin


def inv(d):
    return round(2 ** 30 / ((d * 2 ** 32) / 256))


first = []
for k in range(256):
    z = Fraction(k, 256)
    first.append(max(i for i in range(len(farey) - 1) if farey[i] <= z))

out = ["// Generated by tools/make_tables.py. Edit the script, not this file.",
       "#pragma once", "#include <opxy/types.hpp>", "", "namespace butterfly {", "namespace tables {",
       "using opxy::i16; using opxy::u16; using opxy::u8; using opxy::u32;", ""]
out.append(f"const u32 sine_bits = {SINE_BITS};")
out.append(table("i16", "sine", sine, f"sin(2 pi k / {2 ** SINE_BITS}), Q15; the last entry is the first again"))
out.append(table("u32", "exp2", exp2, "2^(k / 256), Q15 (k = 256: 2 as 65536)"))
out.append(table("u16", "log2m", [min(v, 65535) for v in log2m[:-1]] + [65535], "log2(1 + k / 256), Q16 (the last clamps 1 to 65535)"))
out.append(table("u16", "recip", recip, "2^30 / m at the middle of each of 256 steps of m in [2^15, 2^16): the reciprocal's seed"))
# The spectrum.
SITES, HALF = 17, 9
FLUX_STEPS = 128                      # grid points a turn of flux; 0..1/2 is stored, with the fractions
FLUXES = sorted({Fraction(k, FLUX_STEPS) for k in range(FLUX_STEPS // 2 + 1)} |
                {f for f in farey if f <= Fraction(1, 2)})
LAMBDAS = [0.0, 0.5, 0.8, 1.0, 1.25, 1.6, 2.0]
m = np.arange(SITES) - (SITES - 1) // 2
energy_q12, amp_u8, key_q12 = [], [], []
merged = 0
for flux_point in FLUXES:
    alpha = float(flux_point)
    for lam in LAMBDAS:
        h = np.diag(2 * lam * np.cos(2 * np.pi * alpha * m)) + np.diag(np.ones(SITES - 1), 1) + np.diag(np.ones(SITES - 1), -1)
        e, u = np.linalg.eigh(h)
        a = np.abs(u[(SITES - 1) // 2:, :]).T.copy()     # each state's |psi| at distance 0..8
        k = 0
        while k < SITES - 1:
            if e[k + 1] - e[k] < 2 ** -10:
                a[k] = np.sqrt(a[k] ** 2 + a[k + 1] ** 2)
                a[k + 1] = 0
                e[k + 1] = e[k] = (e[k] + e[k + 1]) / 2
                merged += 1
                k += 2
            else:
                k += 1
        energy_q12 += [int(round(v * 4096)) for v in e]
        amp_u8 += [min(255, int(round(v * 255))) for row in a for v in row]
        # The key: the lowest band's middle, the states within 4% of the span (4 + 4 lambda) of the lowest.
        window = 0.04 * (4 + 4 * lam)
        low = e[e < e[0] + window]
        key_q12.append(int(round(low.mean() * 4096)))
out.append(f"const u32 sites = {SITES}, half_sites = {HALF}, fluxes = {len(FLUXES)}, couplings = {len(LAMBDAS)};")
flux_u32 = [min(0x80000000, round(f * 2 ** 32)) for f in FLUXES]
out.append(table("u32", "flux_point", [f"{v}u" for v in flux_u32], "The fluxes the spectrum is stored at, Q32 turns: 128ths and the fractions to q = 8", 6))
widths = [b - a for a, b in zip(flux_u32, flux_u32[1:])]
out.append(table("u32", "flux_inverse", [f"{round(2 ** 47 / w)}u" for w in widths], "2^47 over each step's width (Q32 turns)", 6))
out.append(table("u8", "flux_first", [max(i for i in range(len(FLUXES) - 1) if flux_u32[i] <= (k << 23)) for k in range(256)],
                 "The step holding flux k / 512 (k = 0..255, up to 1/2)"))
out.append(table("u16", "coupling_q12", [round(v * 4096) for v in LAMBDAS], "The couplings the spectrum is stored at, Q12"))
out.append(table("u32", "coupling_inverse", [round(32768 * 4096 / (round(b * 4096) - round(a * 4096))) for a, b in zip(LAMBDAS, LAMBDAS[1:])], "2^27 over each step between them, Q12"))
out.append(table("i16", "energy", energy_q12, "Each state's energy, Q12, rising: [flux][coupling][state]", 17))
out.append(table("u8", "amplitude", amp_u8, "Each state's |psi| at distance 0..8 from the middle, Q8: [flux][coupling][state][distance]", 18))
out.append(table("i16", "key", key_q12, "The lowest band's middle, Q12: [flux][coupling]", 14))
n = len(farey)
out.append(f"// The snap fractions, the Farey sequence of order 8 from 0 to 1: {', '.join(str(f) for f in farey)}.")
out.append(f"const u32 fraction_count = {n};")
out.append(table("u32", "fraction", [f"{v}u" for v in f_u32], "Each, in Q32 of a turn of flux (1 wraps to 0)", 6))
out.append(table("u8", "numerator", [f.numerator for f in farey], "Each fraction's p and q, in lowest terms"))
out.append(table("u8", "denominator", [f.denominator for f in farey], ""))
out.append(table("u32", "mediant", [f"{v}u" for v in m_u32], "Between neighbours, their mediant: where one's basin meets the next's", 6))
out.append(table("u16", "inverse_low", [inv(d) for d in lo], "2^30 over each basin half's width in Q24: the lower, then the upper"))
out.append(table("u16", "inverse_high", [inv(d) for d in hi], ""))
out.append(table("u8", "first", first, "The interval holding alpha = k / 256"))
out += ["}", "}", ""]
# tables.h: the constants and the tables' declarations; tables_data.h: the
# tables themselves, included once, by engine.cpp.
constants = [line for line in out if line.startswith("const ") or line.startswith("// The snap fractions")]
header = (["// Generated by tools/make_tables.py. Edit the script, not this file.", "#pragma once", "#include <opxy/types.hpp>", "",
           "namespace butterfly {", "namespace tables {", "using opxy::i16; using opxy::u16; using opxy::u8; using opxy::u32;", ""] +
          constants + [""] + DECLARATIONS + ["}", "}", ""])
(ROOT / "tables.h").write_text("\n".join(header))
data = (["// Generated by tools/make_tables.py. Edit the script, not this file.",
         "// The tables, defined once: engine.cpp includes this; everything else includes tables.h.", "#pragma once",
         '#include "tables.h"', "", "namespace butterfly {", "namespace tables {"] + DEFINITIONS + ["}", "}", ""])
(ROOT / "tables_data.h").write_text("\n".join(data))
print("tables.h written;", merged, "mirror pairs merged")
