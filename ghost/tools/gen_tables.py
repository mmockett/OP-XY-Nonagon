#!/usr/bin/env python3
"""Writes tables.h, the fixed-point tables Ghost's engine and screen read: run
it after changing a curve here, and commit both."""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
FS = 44100


def row(values, per_line=8):
    return "\n".join("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ","
                     for i in range(0, len(values), per_line))


def table(kind, name, values, comment):
    return f"// {comment}\nconst {kind} {name}[{len(values)}] = {{\n{row(values)}\n}};\n"


sine = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]
exp2 = [round(65536 * 2 ** (i / 32)) for i in range(33)]
# Head shadow: a one-pole low-pass's coefficient, 1 - e^(-2 pi fc / fs), Q15,
# for fc from 250 Hz to 16 kHz in 32 steps of a sixth of an octave... (6 octaves).
shadow = [round(32767 * (1 - math.exp(-2 * math.pi * 250 * 2 ** (6 * i / 32) / FS))) for i in range(33)]
# The vowels' first two formants (Hz), sung: breath has none (its row is unused).
VOWELS = [("breath", 0, 0), ("oo", 300, 870), ("oh", 500, 900), ("ah", 730, 1090), ("eh", 530, 1840), ("ee", 290, 2290)]
# A Chamberlin filter's frequency coefficient 2 sin(pi f / fs), Q15, at half
# rate (the excitation runs at 22.05 kHz).
formant = []
for _, f1, f2 in VOWELS:
    formant += [round(32768 * 2 * math.sin(2 * math.pi * f1 / FS)), round(32768 * 2 * math.sin(2 * math.pi * f2 / FS))]

out = ["#pragma once",
       "// Generated by tools/gen_tables.py; edit the generator, not this file.",
       "#include <opxy/types.hpp>", "", "namespace ghost {", "",
       table("opxy::i16", "sine_table", sine, "A cycle of sine, Q15, 256 steps and the first again."),
       table("opxy::u32", "exp2_table", exp2, "2^(i/32), Q16."),
       table("opxy::i16", "shadow_table", shadow, "A one-pole low-pass's coefficient for 250 Hz * 2^(6 i / 32), Q15."),
       table("opxy::i16", "formant_table", formant, "Each vowel's two formants (breath, oo, oh, ah, eh, ee) as 2 sin(pi f / (fs / 2)), Q15: the excitation runs at half rate."),
       "}", ""]
(ROOT / "tables.h").write_text("\n".join(out))
