#!/usr/bin/env python3
"""Writes tests/header_font.h: the advance widths of printable ASCII in
Univers Next Pro Light, the OP-XY's header face, which tests/sound.cpp uses
to check that every caption fits its column. The font is stock content and
is not in this repository; XY_FONT gives its path.
    XY_FONT=<path to UniversNextPro-Light.ttf> header_font.py"""
import os
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
font = os.environ.get("XY_FONT")
if not font or not pathlib.Path(font).is_file():
    sys.exit("header_font.py: set XY_FONT to the path of UniversNextPro-Light.ttf")
data = pathlib.Path(font).read_bytes()
tables = {}
for i in range(struct.unpack(">H", data[4:6])[0]):
    tag, _, offset, length = struct.unpack(">4sIII", data[12 + 16 * i:28 + 16 * i])
    tables[tag.decode()] = offset
units = struct.unpack(">H", data[tables["head"] + 18:tables["head"] + 20])[0]
long_metrics = struct.unpack(">H", data[tables["hhea"] + 34:tables["hhea"] + 36])[0]
hmtx = tables["hmtx"]
advances = [struct.unpack(">H", data[hmtx + 4 * i:hmtx + 4 * i + 2])[0] for i in range(long_metrics)]
# cmap, the Unicode BMP subtable (format 4): each character's glyph.
cmap, glyph_of = tables["cmap"], {}
for i in range(struct.unpack(">H", data[cmap + 2:cmap + 4])[0]):
    platform, encoding, offset = struct.unpack(">HHI", data[cmap + 4 + 8 * i:cmap + 12 + 8 * i])
    at = cmap + offset
    if struct.unpack(">H", data[at:at + 2])[0] != 4 or (platform, encoding) not in ((3, 1), (0, 3), (0, 4)):
        continue
    n = struct.unpack(">H", data[at + 6:at + 8])[0] // 2
    ends = struct.unpack(f">{n}H", data[at + 14:at + 14 + 2 * n])
    starts_at = at + 16 + 2 * n
    starts = struct.unpack(f">{n}H", data[starts_at:starts_at + 2 * n])
    deltas = struct.unpack(f">{n}h", data[starts_at + 2 * n:starts_at + 4 * n])
    ranges_at = starts_at + 4 * n
    ranges = struct.unpack(f">{n}H", data[ranges_at:ranges_at + 2 * n])
    for s in range(n):
        for code in range(max(starts[s], 32), min(ends[s], 126) + 1):
            if ranges[s] == 0:
                glyph_of[code] = (code + deltas[s]) & 0xFFFF
            else:
                where = ranges_at + 2 * s + ranges[s] + 2 * (code - starts[s])
                g = struct.unpack(">H", data[where:where + 2])[0]
                glyph_of[code] = (g + deltas[s]) & 0xFFFF if g else 0
    break
widths = [advances[min(glyph_of.get(c, 0), len(advances) - 1)] for c in range(32, 127)]
out = ["#pragma once", "// Generated by tools/header_font.py; edit the generator, not this file.",
       "// Advance widths of ' ' to '~' in Univers Next Pro Light, the OP-XY's",
       "// header face, in font units (header_font_units to the em): the device",
       "// lays text out by these, without kerning.",
       f"const unsigned header_font_units = {units};",
       "const unsigned short header_font_advance[95] = {"]
for i in range(0, 95, 12):
    out.append("    " + ", ".join(str(w) for w in widths[i:i + 12]) + ",")
out += ["};", ""]
(ROOT / "tests/header_font.h").write_text("\n".join(out))
print("tests/header_font.h")
